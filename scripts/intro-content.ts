export function createIntroduction(book: IntroBook): string {
  const category = book.category.toLowerCase();
  let paragraphs: string[];
  if (/ธุรกิจ|การเงิน|ผู้ประกอบการ/.test(category)) paragraphs = business(book);
  else if (/พัฒนา|แรงบันดาลใจ|ชีวิต/.test(category)) paragraphs = selfHelp(book);
  else if (/กวี|บทกวี/.test(category)) paragraphs = poetry(book);
  else if (/เทคโนโลยี|วิทยาศาสตร์|ดิจิทัล/.test(category)) paragraphs = technology(book);
  else if (/สารคดี|ความเรียง|ประวัติ|ความรู้/.test(category)) paragraphs = nonfiction(book);
  else paragraphs = fiction(book, book.id);
  return paragraphs.join("\n\n");
}
